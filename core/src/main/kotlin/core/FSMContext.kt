package core

/**
 * FSMContext - контекст конечного автомата для разделения состояний
 * Позволяет разделять логику работы с мемами и подборками
 */
enum class FSMContext {
    MEMES,           // Контекст мемов - избранное мемы, история мемов
    COLLECTIONS      // Контекст подборок - избранное фильмы/сериалы/книги/игры
}
